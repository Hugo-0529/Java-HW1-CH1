// 主題：常數(literal) —— 輸出字元、字串、數值
public class HW1_P16 {
    public static void main(String[] args) {
        System.out.println('A');              // 字元常數：用單引號
        System.out.println("歡迎使用Java!");   // 字串常數：用雙引號
        System.out.println(123);              // 數值常數：不需引號
    }
}
